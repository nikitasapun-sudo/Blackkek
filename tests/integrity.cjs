'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8'),core=fs.readFileSync('omega_v34_core.js','utf8');
for(const s of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new vm.Script(s[1]);
assert.equal(html.match(/<script id="omegaCore">([\s\S]*?)<\/script>/)[1],core);
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));assert.equal(manifest.display,'standalone');
for(const icon of manifest.icons)assert.ok(fs.existsSync(icon.src));
const sw=fs.readFileSync('sw.js','utf8');new vm.Script(sw);new vm.Script(fs.readFileSync('omega_worker.js','utf8'));
for(const f of ['./','./index.html','./manifest.webmanifest','./icons/icon.svg','./omega_worker.js','./omega_v34_core.js'])assert.ok(sw.includes("'"+f+"'"));
assert.ok(html.includes("navigator.serviceWorker.register('./sw.js')"));assert.ok(html.includes("new Worker('./omega_worker.js')"));
console.log('PASS PWA integrity: identical embedded mathematical core, valid scripts, manifest and offline assets');
